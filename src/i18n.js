function normalizeLanguage(lang) {
  return Object.hasOwn(LANGUAGES, lang) ? lang : DEFAULT_LANGUAGE;
}

/** Translate `key` for `lang`, filling {placeholders} from `vars`. Missing keys fall back to English. */
function t(lang, key, vars = {}) {
  const table = messages[normalizeLanguage(lang)];
  const template = table[key] ?? messages[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

module.exports = { t, LANGUAGES, DEFAULT_LANGUAGE, normalizeLanguage, messages };
